// Captures the Devpost gallery screenshots from a running build: node scripts/screens.mjs http://127.0.0.1:4173/ OUT_DIR
import { chromium } from '@playwright/test'

const [url, out] = process.argv.slice(2)
const browser = await chromium.launch({ channel: 'chrome' })
const desk = await browser.newPage({ viewport: { width: 1440, height: 960 }, deviceScaleFactor: 2 })
await desk.goto(url)
await desk.screenshot({ path: `${out}/01-start.png` })
await desk.getByRole('button', { name: 'Try a sample photo' }).click()
const card = desk.getByRole('listitem').filter({ hasText: 'sofa-for-sale.jpg' })
await card.waitFor()
await card.scrollIntoViewIfNeeded()
await card.screenshot({ path: `${out}/02-findings.png` })
await card.getByRole('button', { name: 'Make a clean copy' }).click()
await card.getByRole('status').waitFor()
await card.screenshot({ path: `${out}/03-clean-copy.png` })
const phone = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 3 })
await phone.goto(url)
await phone.getByRole('button', { name: 'Try a sample photo' }).click()
await phone.getByRole('listitem').first().waitFor()
await phone.getByRole('listitem').first().scrollIntoViewIfNeeded()
await phone.screenshot({ path: `${out}/04-phone.png` })
await browser.close()
console.log('saved')
