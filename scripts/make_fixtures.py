"""Build small synthetic test photos with known metadata (written by exiftool, an independent implementation) and
emit them as base64 in src/fixtures.ts. All values are synthetic: the GPS point is the Eiffel Tower, names are fake.

usage: python3 scripts/make_fixtures.py   (needs Pillow and exiftool on PATH)
"""
import base64
import subprocess
import tempfile
from pathlib import Path

from PIL import Image, ImageDraw

HERE = Path(__file__).resolve().parent.parent
OUT = HERE / "src" / "fixtures.ts"


def picture(w, h):
    im = Image.new("RGB", (w, h), (210, 225, 240))
    d = ImageDraw.Draw(im)
    d.rectangle([w // 6, h // 3, w * 5 // 6, h * 5 // 6], fill=(120, 80, 60))
    d.ellipse([w // 2, h // 10, w // 2 + h // 4, h // 10 + h // 4], fill=(250, 200, 60))
    return im


def exiftool(path, *args):
    subprocess.run(["exiftool", "-q", "-overwrite_original", *args, str(path)], check=True)


def main():
    tmp = Path(tempfile.mkdtemp())
    thumb = tmp / "thumb.jpg"
    picture(32, 24).save(thumb, quality=70)

    jpg = tmp / "sample.jpg"
    picture(64, 48).save(jpg, quality=85)
    exiftool(jpg, "-GPSLatitude=48.85837", "-GPSLatitudeRef=N", "-GPSLongitude=2.29448", "-GPSLongitudeRef=E",
             "-GPSAltitude=35", "-GPSAltitudeRef=0", "-Artist=Sample Owner", "-Make=Example Phone Co.",
             "-Model=Sample X1", "-DateTimeOriginal=2026:10:18 14:32:05", "-SerialNumber=SN-0000-DEMO",
             "-Orientation#=6", "-XMP-photoshop:City=Paris", "-IPTC:By-line=Sample Owner", "-Comment=test comment",
             f"-ThumbnailImage<={thumb}")
    data = jpg.read_bytes() + b"TRAILER-DATA-AFTER-EOI"
    jpg.write_bytes(data)

    png = tmp / "sample.png"
    picture(32, 24).save(png)
    exiftool(png, "-GPSLatitude=48.85837", "-GPSLatitudeRef=N", "-GPSLongitude=2.29448", "-GPSLongitudeRef=E",
             "-PNG:Author=Sample Owner")

    webp = tmp / "sample.webp"
    picture(32, 24).save(webp, quality=80)
    exiftool(webp, "-GPSLatitude=48.85837", "-GPSLatitudeRef=N", "-GPSLongitude=2.29448", "-GPSLongitudeRef=E",
             "-XMP-dc:Creator=Sample Owner")

    plain = tmp / "plain.jpg"
    picture(16, 12).save(plain, quality=80)

    lines = ["// Generated by scripts/make_fixtures.py: synthetic images with metadata written by exiftool.",
             "// GPS = the Eiffel Tower (48.85837 N, 2.29448 E); names are fake.", ""]
    for name, p in [("jpegWithEverything", jpg), ("pngWithExif", png), ("webpWithExif", webp), ("plainJpeg", plain)]:
        lines.append(f"export const {name} = '{base64.b64encode(p.read_bytes()).decode()}'")
    lines.append("")
    lines.append("export function bytes(b64: string): Uint8Array {")
    lines.append("  const bin = atob(b64)")
    lines.append("  const out = new Uint8Array(bin.length)")
    lines.append("  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i)")
    lines.append("  return out")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT, {n: p.stat().st_size for n, p in [("jpg", jpg), ("png", png), ("webp", webp), ("plain", plain)]})


if __name__ == "__main__":
    main()
